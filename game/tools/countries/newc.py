def frame(cfg, polys):
    """Grid origin and size from the outline, with room for posts and labels around it."""
    lons=[p[0] for poly in polys for p in poly]; lats=[p[1] for poly in polys for p in poly]
    latc=(min(lats)+max(lats))/2; kx=111*math.cos(math.radians(latc))
    cfg['latc']=latc
    cfg['_span']=(min(lons),max(lons),min(lats),max(lats),kx)
    return cfg
def sized(cfg, w):
    lo1,lo2,la1,la2,kx=cfg['_span']; S=w/math.sqrt(3)
    m=2.2
    c=dict(cfg); c['w']=w
    c['lon0']=lo1-m*w/kx; c['lat0']=la2+m*1.5*S/111
    c['cols']=int((lo2-lo1)*kx/w+2*m+2); c['rows']=int((la2-la1)*111/(1.5*S)+2*m+2)
    return c
def fit(cfg, lo, hi, w0):
    w=w0
    for _ in range(300):
        n=tsgen.tiles_at(sized(cfg,w),w)
        if lo<=n<=hi: return w,n
        w*= 1.025 if n>hi else 0.975
    raise SystemExit(f"{cfg['name']}: no size for {lo}-{hi}, last {n}")

